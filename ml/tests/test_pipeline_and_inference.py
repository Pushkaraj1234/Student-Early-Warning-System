def test_valid_request_returns_contract(service: InferenceService, trained: dict[str, Any]) -> None:
    result = service.predict_safe(_payload(trained, top_k=3))
    assert result["ok"] is True
    data = result["data"]
    uuid.UUID(data["prediction_id"])
    assert data["model_version"] == trained["summary"]["active_model_version"]
    assert 0.0 <= data["risk_probability"] <= 1.0
    assert data["risk_level"] in {"stable", "watch", "elevated", "high"}
    assert data["data_provenance"] == "synthetic"
    assert data["api_version"] == "1.0.0"
    assert data["target"] == "academic"
    factors = data["top_factors"]
    assert 1 <= len(factors) <= 3
    assert [f["rank"] for f in factors] == list(range(1, len(factors) + 1))
    magnitudes = [abs(f["contribution"]) for f in factors]
    assert magnitudes == sorted(magnitudes, reverse=True)
    for f in factors:
        assert f["feature"] in FEATURE_NAMES
        assert f["direction"] == ("increases_risk" if f["contribution"] > 0 else "decreases_risk")
        assert set(f) == {"feature", "contribution", "direction", "rank", "feature_value"}


