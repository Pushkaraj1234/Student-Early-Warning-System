STUDENT_FORBIDDEN = ("risk", "fail", "withdraw", "dropout", "drop out", "probability", "model", "%", "shap")


@pytest.mark.parametrize("row", [0, 1, 2, 3, 4, 5])
def test_student_explanation_is_non_stigmatising(
    service: InferenceService, trained: dict[str, Any], row: int
) -> None:
    response = service.predict(_payload(trained, row=row))
    metadata = ModelRegistry(trained["registry_root"]).load(response.model_version).metadata
    text = json.dumps(for_student(response, metadata).as_dict()).lower()
    assert not any(word in text for word in STUDENT_FORBIDDEN)
    assert not any(ch.isdigit() for ch in text)  # no values, scores or probabilities
    assert not any(f in text for f in FEATURE_NAMES)  # no model feature keys


def test_student_themes_come_only_from_factors_that_raised_the_estimate(
    service: InferenceService, trained: dict[str, Any]
) -> None:
    registry = ModelRegistry(trained["registry_root"])
    for row in range(len(trained["rows"])):
        response = service.predict(_payload(trained, row=row, top_k=10))
        explanation = for_student(response, registry.load(response.model_version).metadata)
        if response.risk_level == "stable":
            assert explanation.focus_areas == ()
            continue
        allowed = {
            THEME_TEXT[t][0]
            for f in response.top_factors
            if f.direction == "increases_risk" and (t := student_theme(f.feature)) is not None
        }
        titles = [a.title for a in explanation.focus_areas]
        assert set(titles) <= allowed and len(titles) == len(set(titles)) <= 3


