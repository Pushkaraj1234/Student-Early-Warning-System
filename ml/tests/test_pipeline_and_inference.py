def test_every_model_is_saved_with_preprocessing_and_lineage(trained: dict[str, Any]) -> None:
    cutoff = trained["summary"]["cutoffs"][0]
    for name in MODELS:
        version = cutoff["models"][name]["model_version"]
        artifact = ModelArtifact.load(trained["registry_root"] / version)
        meta = artifact.metadata
        assert meta.feature_names == FEATURE_NAMES
        assert meta.feature_version == FEATURE_VERSION
        assert meta.dataset_version.startswith("oulad-")
        assert meta.data_provenance == "synthetic"
        assert meta.training_timestamp.tzinfo is not None
        assert meta.risk_thresholds.watch < meta.risk_thresholds.elevated < meta.risk_thresholds.high
        assert {
            "validation",
            "test",
            "test_bootstrap_ci",
            "test_calibration_comparison",
            "stability",
            "subgroups_test",
            "drift_train_vs_test",
            "monitoring_snapshot_test",
        } <= set(meta.metrics)
        assert meta.target == "academic"
        assert meta.leakage_check["passed"] is True
        # calibration is recorded as applied only when the out-of-time check says it helps
        decision = meta.calibration_decision
        assert decision["check_split"]["evaluate"] == ["2014B"]
        improved = decision["brier_calibrated"] < decision["brier_raw"] and (
            decision["ece_calibrated"] < decision["ece_raw"]
        )
        assert decision["apply"] is improved
        assert (meta.calibration_method == "none") is (not improved)
        assert len(meta.model_sha256) == 64
        steps = list(artifact.pipeline.named_steps)
        assert steps[-1] == "model"
        if name != "xgboost":
            assert "impute" in steps  # preprocessing travels with the model
        if name == "logistic_regression":
            assert "scale" in steps and artifact.background_means is not None


