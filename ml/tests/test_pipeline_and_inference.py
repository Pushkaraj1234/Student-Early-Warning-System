def test_mentor_and_admin_explanations(service: InferenceService, trained: dict[str, Any]) -> None:
    response = service.predict(_payload(trained, top_k=5))
    metadata = ModelRegistry(trained["registry_root"]).load(response.model_version).metadata
    mentor = for_mentor(response, metadata)
    assert [f.feature for f in mentor.factors] == [f.feature for f in response.top_factors]
    assert mentor.risk_probability == response.risk_probability
    assert any("not causes" in c for c in mentor.caveats)
    assert any("synthetic" in c for c in mentor.caveats)  # provenance warning
    admin = for_admin(response, metadata)
    assert admin.provenance_permits_live_use is False
    assert admin.model_version == response.model_version
    assert "student_id" not in json.dumps(admin.as_dict())
    assert admin.calibration_reason == metadata.calibration_decision["reason"]


