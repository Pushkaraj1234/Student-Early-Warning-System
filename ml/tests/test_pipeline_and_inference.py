def test_registry_export_scoping_rules(trained: dict[str, Any]) -> None:
    version = trained["summary"]["active_model_version"]
    metadata = ModelRegistry(trained["registry_root"]).load(version).metadata
    with pytest.raises(RegistryExportError, match="only institutional"):
        registry_row(metadata, institution_id=uuid.uuid4())
    institutional = metadata.model_copy(update={"data_provenance": "institutional"})
    with pytest.raises(RegistryExportError, match="must name the institution"):
        registry_row(institutional)
    assert registry_row(institutional, institution_id=uuid.UUID(int=1))["institution_id"] == str(
        uuid.UUID(int=1)
    )
